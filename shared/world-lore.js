  function getPlace(id) {
    if (!id) return null;
    return PLACES[String(id).toLowerCase()] || null;
  }

  function listPlaces() {
    return PLACE_ORDER.map(function (id) { return PLACES[id]; }).filter(Boolean);
  }

  function placesByLevel(level) {
    var lv = level | 0;
    return listPlaces().filter(function (p) {
      if (!p.level || !p.level.length) return false;
      return lv >= p.level[0] && lv <= p.level[1];
    });
  }

  function pathLabel(classData) {
    if (!classData) return '';
    var path = classData.path;
    if (path === 'tech' || path === 'mystic') {
      return PATH_LORE.tech.name + ' · ' + (classData.pathSubtitle || PATH_LORE.tech.subtitle);
    }
    return PATH_LORE.fighter.name + ' · ' + (classData.pathSubtitle || PATH_LORE.fighter.subtitle);
  }

  function formatStatsLine(bs) {
    bs = bs || {};
    var hp = bs.hp != null ? bs.hp : '—';
    var en = bs.energy != null ? bs.energy : '—';
    var atk = bs.attack != null ? bs.attack : '—';
    var def = bs.defense != null ? bs.defense : '—';
    var catk = bs.cAtk != null ? bs.cAtk : (bs.mAtk != null ? bs.mAtk : '—');
    return (
      TERMS.hpShort + ' ' + hp +
      ' · ' + TERMS.energyShort + ' ' + en +
      ' · ' + TERMS.pAtkShort + ' ' + atk +
      ' · ' + TERMS.pDefShort + ' ' + def +
      ' · ' + TERMS.cAtkShort + ' ' + catk
    );
  }

  function historyAsHtml() {
    return WORLD_HISTORY.map(function (h) {
      var years = h.years ? ' <em>(' + h.years + ')</em>' : '';
      return '<p><strong>' + h.era + '</strong>' + years + '. ' + h.text + '</p>';
    }).join('');
  }

  function historyAsText() {
    return WORLD_HISTORY.map(function (h) {
      var head = h.era + (h.years ? ' (' + h.years + ')' : '');
      return head + '\n' + h.text;
    }).join('\n\n');
  }

  function placesAsText() {
    return listPlaces().map(function (p) {
      var lv = p.level ? ' [ур. ' + p.level[0] + '–' + p.level[1] + ']' : ' [данж]';
      var peace = p.peace ? ' · мирная' : '';
      return p.name + lv + peace + '\n  ' + p.blurb;
    }).join('\n\n');
  }

