/** Совместимость: старый код читал window.QUEST_DATABASE[id].name/levelReq/rewards. */
function buildQuestDatabase() {
    const out = {};
    const QDB = window.QUEST_DB;
    if (!QDB || typeof QDB.all !== 'function') return out;
    QDB.all().forEach((q) => {
        out[q.id] = Object.assign({}, q, { dialogue: QUEST_DIALOGUES[q.id] || null });
    });
    return out;
}

const QUEST_DATABASE = buildQuestDatabase();

// ============================================
// МЕНЕДЖЕР КВЕСТОВ — зеркало сервера
// ============================================
class QuestManager {
    constructor() {
        /** id → { id, state, progress:[] } из последнего пакета quests */
        this.quests = {};
        /** id → сколько раз сдан */
        this.doneById = {};
        /** id доступных к принятию (считает сервер: уровень, цепочка, daily) */
        this.availableIds = [];
        this._lastState = {};
    }

    // ---- Приём серверного состояния ----

    /** Применить пакет `quests` (welcome и после каждого изменения). */
    applyServerState(snap) {
        if (!snap) return;
        const prev = this._lastState;
        this.quests = {};
        (snap.active || []).forEach((e) => {
            const tpl = QUEST_DATABASE[e.id];
            this.quests[e.id] = {
                id: e.id,
                template: tpl || null,
                state: e.state,
                progress: Array.isArray(e.progress) ? e.progress.slice() : [],
                objectives: this._mergeObjectives(tpl, e.progress)
            };
        });
        this.doneById = {};
        (snap.done || []).forEach((d) => { this.doneById[d.id] = d.n || 1; });
        this.availableIds = (snap.available || []).slice();

        // «Готов к сдаче» — сообщить один раз на переход состояния
        Object.keys(this.quests).forEach((id) => {
            const st = this.quests[id].state;
            if (st === QUEST_STATES.COMPLETABLE && prev[id] !== QUEST_STATES.COMPLETABLE) {
                const nm = this.quests[id].template ? this.quests[id].template.name : id;
                if (window.game && window.game.addChatMessage) {
                    window.game.addChatMessage('Задание готово к сдаче: ' + nm, 'loot');
                }
            }
        });
        this._lastState = {};
        Object.keys(this.quests).forEach((id) => { this._lastState[id] = this.quests[id].state; });

        this._refreshUI();
    }

    /** Цели с текущим прогрессом — формат, который ждёт UI. */
    _mergeObjectives(tpl, progress) {
        if (!tpl || !Array.isArray(tpl.objectives)) return [];
        return tpl.objectives.map((o, i) => Object.assign({}, o, {
            current: Array.isArray(progress) ? (progress[i] | 0) : 0
        }));
    }

    _refreshUI() {
        const g = window.game;
        if (!g) return;
        if (g.charMenu && g.charMenu.isOpen && g.charMenu.activeTab === 'quest' &&
            typeof g.charMenu.renderQuest === 'function') {
            try { g.charMenu.renderQuest(); } catch (e) { /* ignore */ }
        }
        if (g.npcUI && g.npcUI.isOpen && g.npcUI.isOpen() &&
            typeof g.npcUI.renderMainDialogue === 'function') {
            try { g.npcUI.renderMainDialogue(); } catch (e) { /* ignore */ }
        }
        if (g.npcManager && typeof g.npcManager.refreshQuestIndicators === 'function') {
            try { g.npcManager.refreshQuestIndicators(); } catch (e) { /* ignore */ }
        }
    }

    // ---- Интенты (авторитет сервера) ----

    /** Принять квест. Сервер проверит уровень, цепочку, дистанцию до NPC. */
    startQuest(questId) {
        const net = window.game && window.game.net;
        if (!net || typeof net.intentQuestAccept !== 'function') {
            if (window.game) window.game.addChatMessage('Нет связи с сервером.', 'system');
            return false;
        }
        net.intentQuestAccept(questId);
        // Стартовый диалог показываем сразу: отказ придёт пакетом quest_fail.
        const d = QUEST_DIALOGUES[questId];
        if (d && d.start && window.game && window.game.dialogueUI) {
            window.game.dialogueUI.showDialogue(d.start);
        }
        return true;
    }

    /** Сдать квест. Награды выдаёт сервер (quest_complete_ok → applyInv). */
    completeQuest(questId, rewardChoice) {
        const net = window.game && window.game.net;
        if (!net || typeof net.intentQuestComplete !== 'function') {
            if (window.game) window.game.addChatMessage('Нет связи с сервером.', 'system');
            return false;
        }
        net.intentQuestComplete(questId, rewardChoice);
        return true;
    }

    /** Отказаться от квеста (прогресс теряется). */
    abandonQuest(questId) {
        const net = window.game && window.game.net;
        if (!net || typeof net.intentQuestAbandon !== 'function') return false;
        net.intentQuestAbandon(questId);
        return true;
    }

    /** Показать диалог завершения (зовётся из обработчика quest_complete_ok). */
    showCompleteDialogue(questId) {
        const d = QUEST_DIALOGUES[questId];
        if (d && d.complete && window.game && window.game.dialogueUI) {
            window.game.dialogueUI.showDialogue(d.complete);
        }
    }

    // ---- Чтение состояния (для UI) ----

    getActiveQuests() {
        return Object.keys(this.quests).map((id) => this.quests[id]);
    }

    getQuestById(id) {
        return this.quests[id] || null;
    }

    isCompleted(id) {
        return !!this.doneById[id];
    }

    isAvailable(id) {
        return this.availableIds.indexOf(id) >= 0;
    }

    isActive(id) {
        return !!this.quests[id];
    }

    stateOf(id) {
        const q = this.quests[id];
        if (q) return q.state;
        if (this.doneById[id]) return QUEST_STATES.COMPLETED;
        return QUEST_STATES.NOT_STARTED;
    }
}

